//go:build integration

package mysql

import (
	"testing"

	"github.com/google/uuid"
	"github.com/stablyai/orca-go/services/request-service/internal/adapter/contracttest"
)

// A project that saved its engine settings before migration 0101 keeps them and reads as automatic Plan generation on.
func TestMySQL_PlanAutoGenerateDefaultsOnForOldRows(t *testing.T) {
	db, admin := startMySQL(t)
	before, from := contracttest.SplitMigrationsAt(t, contracttest.MigrationScripts(t, "mysql", "up"), "plan_auto_jobs")
	applyScripts(t, admin, before)
	tenantID, projectID := uuid.NewString(), uuid.NewString()
	if _, err := admin.Exec(`INSERT INTO project_engine_settings (tenant_id, project_id, solution_engine, updated_by) VALUES (?, ?, 'native', ?)`,
		tenantID, projectID, uuid.NewString()); err != nil {
		t.Fatal(err)
	}
	applyScripts(t, admin, from)

	got, found, err := NewProjectEngineSettingsRepository(New(db)).Get(contracttest.CtxForTenant(tenantID), projectID)
	if err != nil || !found || !got.PlanAutoGenerate || got.Engine != "native" || got.Version != 1 {
		t.Fatalf("old row: %+v found=%v err=%v", got, found, err)
	}
}
