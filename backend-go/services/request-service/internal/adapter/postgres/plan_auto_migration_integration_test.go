//go:build integration

package postgres

import (
	"context"
	"testing"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/stablyai/orca-go/services/request-service/internal/adapter/contracttest"
)

// A project that saved its engine settings before migration 0101 keeps them and reads as automatic Plan generation on.
func TestPostgres_PlanAutoGenerateDefaultsOnForOldRows(t *testing.T) {
	adminDSN, admin := startPostgres(t)
	before, from := contracttest.SplitMigrationsAt(t, contracttest.MigrationScripts(t, "postgres", "up"), "plan_auto_jobs")
	applyScripts(t, admin, before)
	tenantID, projectID := uuid.NewString(), uuid.NewString()
	ctx := context.Background()
	if _, err := admin.Exec(ctx, `INSERT INTO request.project_engine_settings (tenant_id, project_id, solution_engine, updated_by) VALUES ($1, $2, 'native', $3)`,
		tenantID, projectID, uuid.NewString()); err != nil {
		t.Fatal(err)
	}
	applyScripts(t, admin, from)

	pool, err := pgxpool.New(ctx, adminDSN)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(pool.Close)
	got, found, err := NewProjectEngineSettingsRepository(New(pool)).Get(contracttest.CtxForTenant(tenantID), projectID)
	if err != nil || !found || !got.PlanAutoGenerate || got.Engine != "native" || got.Version != 1 {
		t.Fatalf("old row: %+v found=%v err=%v", got, found, err)
	}
}
