"""Script generators. `claude`: Claude CLI in print mode, run inside the worktree with file tools only. `template`: deterministic
skeleton from TCIR (option B), for dry runs and as a starting point when no model is available."""
from __future__ import annotations

import json
import os
import shutil
import subprocess
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path

from .conformance import OPS, _num
from .conventions import Conventions
from .errors import GeneratorError
from .planner import FilePlan, slug
from .tcir import SCHEMA_VERSION

# Read/write tools only: no Bash (cannot run tests or reach the app), no web, no MCP (TCIR is in the prompt).
CLAUDE_TOOLS = "Read,Write,Edit,Glob,Grep"


@dataclass
class Request:
    worktree: Path
    plan: FilePlan
    feature: str
    spec_version: int
    conventions: Conventions
    feedback: list[str] = field(default_factory=list)


@dataclass
class Result:
    ok: bool
    detail: str = ""
    cost_usd: float = 0.0


class TemplateGenerator:
    name = "template"

    def generate(self, req: Request) -> Result:
        path = req.worktree / req.plan.path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render_template(req), encoding="utf-8")
        return Result(True, "template")


def _assert_line(case_id: str, e: dict) -> str:
    observed = f"tsa_driver.observe({e['id']!r}, {e.get('kind')!r})"
    op, value = str(e.get("op") or ""), e.get("value")
    if op in OPS.values():
        num = _num(value) if op in ("<", "<=", ">", ">=") else None
        literal = repr(value) if num is None else repr(int(num) if num.is_integer() else num)
        return f"    assert {observed} {op} {literal}  # @exp {e['id']}"
    return f"    assert {observed}  # @exp {e['id']}"


def render_template(req: Request) -> str:
    lines = [f'"""Generated by TSA (template) from TCIR {req.feature} v{req.spec_version}, group {req.plan.group}.',
             "",
             "Implement the `tsa_driver` fixture (step + observe) in conftest.py. Lines tagged @exp come from the spec: do not edit them.",
             '"""', "import pytest", ""]
    used = set()
    for c in req.plan.cases:
        name = f"test_{slug(c['id'])}"
        while name in used:
            name += "_"
        used.add(name)
        lines += ["", f"@pytest.mark.tc({c['id']!r}, spec_version={req.spec_version})", f"def {name}(tsa_driver):",
                  f"    {json.dumps(c.get('objective', ''), ensure_ascii=False)}"]
        for s in c.get("steps") or []:
            lines.append(f"    # {s['id']} {s.get('kind')}: {s.get('action', '')}".replace("\n", " "))
            lines.append(f"    tsa_driver.step({s['id']!r}, {s.get('kind')!r}, {s.get('input')!r})")
        lines += [_assert_line(c["id"], e) for e in c.get("expected") or []]
    return "\n".join(lines) + "\n"


def build_prompt(req: Request) -> str:
    tpl = resources.files("tsa").joinpath("prompts/generate.md").read_text(encoding="utf-8")
    conv = req.conventions
    samples = "\n\n".join(f"`{p}`:\n\n```python\n{t}\n```" for p, t in conv.samples) or "(none)"
    feedback = ""
    if req.feedback:
        feedback = ("\n## Fix round\n\nThe file already exists. Fix ONLY these problems; do not change any line that carries `# @exp` "
                    "unless a problem below names that @exp id:\n\n" + "\n".join(f"- {f}" for f in req.feedback) + "\n")
    values = {"file": req.plan.path, "spec_version": str(req.spec_version), "feedback": feedback, "tests_dir": conv.tests_dir,
              "fixtures": ", ".join(f"`{f}`" for f in conv.fixtures) or "(none)", "samples": samples, "schema": SCHEMA_VERSION,
              "feature": req.feature, "cases": json.dumps(req.plan.cases, ensure_ascii=False, indent=1),
              "exp_ids": ", ".join(e["id"] for c in req.plan.cases for e in c.get("expected") or [])}
    for k, v in values.items():
        tpl = tpl.replace("{{" + k + "}}", v)
    return tpl


@dataclass
class ClaudeCliGenerator:
    model: str | None = None
    binary: str = "claude"
    timeout_s: int = 900
    name: str = "claude"

    def command(self, prompt: str) -> list[str]:
        cmd = [self.binary, "-p", prompt, "--output-format", "json", "--tools", CLAUDE_TOOLS, "--allowedTools", CLAUDE_TOOLS,
               "--strict-mcp-config", "--permission-mode", "acceptEdits"]
        if self.model:
            cmd += ["--model", self.model]
        return cmd

    def generate(self, req: Request) -> Result:
        exe = shutil.which(self.binary)
        if not exe:
            raise GeneratorError(f"{self.binary!r} not found on PATH")
        env = {k: v for k, v in os.environ.items() if not k.startswith("CLAUDE_CODE_SSE")}
        try:
            proc = subprocess.run(self.command(build_prompt(req)), cwd=req.worktree, capture_output=True, text=True, timeout=self.timeout_s,
                                  env=env)
        except subprocess.TimeoutExpired:
            return Result(False, f"claude timed out after {self.timeout_s}s")
        try:
            out = json.loads(proc.stdout or "{}")
        except ValueError:
            out = {}
        cost = float(out.get("total_cost_usd") or 0.0)
        if proc.returncode != 0 or out.get("is_error"):
            return Result(False, (out.get("result") or proc.stderr or proc.stdout or "claude failed")[:500], cost)
        return Result(True, str(out.get("result") or "")[:500], cost)


def make(name: str, model: str | None = None) -> TemplateGenerator | ClaudeCliGenerator:
    if name == "template":
        return TemplateGenerator()
    if name == "claude":
        return ClaudeCliGenerator(model=model)
    raise GeneratorError(f"unknown generator {name!r}; expected claude or template")
